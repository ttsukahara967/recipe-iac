def seed_recipes(conn: Connection) -> None:
    stmt = insert(Recipe).values(RECIPES)
    stmt = stmt.on_conflict_do_update(
        index_elements=[Recipe.slug],
        set_={name: stmt.excluded[name] for name in _UPDATABLE},
    )
    conn.execute(stmt)
